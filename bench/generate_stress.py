def t_long_chain(i, steps):
    b, d = f"b{i}", f"d{i}"
    x = [b, 16, d]
    L = [f"def long_chain_{i}(x: {ann(x)}):"]
    pool = {tuple(x): ["x"]}
    cur_name, cur = "x", list(x)
    nacts = ["jnp.tanh", "jax.nn.relu", "jax.nn.gelu", "jax.nn.sigmoid", "jnp.exp", "jnp.abs"]
    for s in range(steps):
        nm = f"v{s}"
        op = G.r.random()
        shp = list(cur)
        rank = len(cur)
        if op < 0.22:
            expr = f"{cur_name} * {G.pick(['0.5', '2.0', '1.5', '3'])}"
        elif op < 0.40:
            expr = f"{G.pick(nacts)}({cur_name})"
        elif op < 0.52 and len(pool[tuple(cur)]) > 1:
            other = G.pick(pool[tuple(cur)])
            expr = f"{cur_name} + {other}"
        elif op < 0.62 and rank > 2:
            ax = G.r.randint(0, rank - 1)
            fn = G.pick(["sum", "mean", "max"])
            expr = f"{cur_name}.{fn}(axis={ax})" if fn != "max" else f"jnp.max({cur_name}, axis={ax})"
            shp = cur[:ax] + cur[ax + 1 :]
        elif op < 0.72 and rank < 4:
            ax = G.r.randint(0, rank)
            expr = f"jnp.expand_dims({cur_name}, axis={ax})"
            shp = cur[:ax] + [1] + cur[ax:]
        elif op < 0.80 and rank >= 2:
            i1, i2 = sorted(G.r.sample(range(rank), 2))
            expr = f"jnp.swapaxes({cur_name}, {i1}, {i2})"
            shp = list(cur)
            shp[i1], shp[i2] = shp[i2], shp[i1]
        elif op < 0.86:
            expr = f"jax.nn.softmax({cur_name}, axis=-1)"
        elif op < 0.92 and rank >= 3:
            expr = f"{cur_name}[:, 0]"
            shp = [cur[0]] + cur[2:]
        elif op < 0.96 and rank >= 2 and any(isinstance(v, int) for v in cur):
            axes = [a for a, v in enumerate(cur) if isinstance(v, int)]
            ax = G.pick(axes)
            expr = f"jnp.concatenate([{cur_name}, {cur_name}], axis={ax})"
            shp = list(cur)
            shp[ax] = cur[ax] * 2
        elif rank >= 2:
            expr = f"{cur_name}.T"
            shp = list(reversed(cur))
        else:
            expr = f"{cur_name} * 2.0"
        # keep shapes tame
        if len(shp) < 2 or len(shp) > 4 or any(isinstance(v, int) and v > 4096 for v in shp):
            expr = f"{cur_name} * 2.0"
            shp = list(cur)
        line = f"    {nm} = {expr}"
        if s % 5 == 0:
            line += es(**{nm: shp})
        L.append(line)
        pool.setdefault(tuple(shp), []).append(nm)
        cur_name, cur = nm, shp
    L.append(f"    return {cur_name}")
    L += ["", ""]
    return L


