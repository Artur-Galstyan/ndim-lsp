def t_einops(i):
    L = []
    b, n = f"b{i}", f"n{i}"
    d = G.pick([16, 32, 64])
    x = [b, n, d]
    L.append(f"def einops_soup_{i}(x: {ann(x)}):")
    names = {"b": b, "n": n, "d": d}
    cases = [
        ("rearrange", "b n d -> b (n d)", {}, [b, f"{n}*{d}"]),
        ("rearrange", "b n d -> (b n) d", {}, [f"{b}*{n}", d]),
        ("rearrange", "b n d -> d n b", {}, [d, n, b]),
        ("rearrange", "b n (h e) -> b h n e", {"h": 4}, [b, 4, n, d // 4]),
        ("reduce", "b n d -> b d", "mean", [b, d]),
        ("reduce", "b n d -> b", "max", [b]),
        ("reduce", "b n d -> n", "sum", [n]),
        ("repeat", "b n d -> b n d k", {"k": 3}, [b, n, d, 3]),
        ("repeat", "b n d -> r b n d", {"r": 2}, [2, b, n, d]),
    ]
    G.r.shuffle(cases)
    for k, (op, pat, extra, out) in enumerate(cases[: G.r.randint(4, 7)]):
        if op == "reduce":
            call = f'reduce(x, "{pat}", "{extra}")'
        else:
            kws = "".join(f", {a}={v}" for a, v in extra.items())
            call = f'{op}(x, "{pat}"{kws})'
        L.append(f"    e{k} = {call}{es(**{f'e{k}': out})}")
    L.append("    return e0")
    L.append("")
    L.append("")
    return L


