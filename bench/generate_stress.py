def t_comprehensions(i):
    # A list comprehension over an array takes one row at each step. Passed to
    # stack or concatenate it has the shape of one element and, when the
    # iterable has a numeric length, that many elements. zip stops at the
    # shortest argument, range counts its own items, and sum starts from the
    # integer 0, so it keeps the element shape. The loop variable does not
    # leak, and it hides a variable of the same name outside. A symbolic
    # length, a filter, a generator (numpy, jax and torch reject it in stack),
    # and a dim that is spelled with the loop variable stay unknown.
    n, d, k = 3 + i % 4, 8 + 2 * (i % 4), 5 + i % 3
    sym = f"s{i}"
    return [
        f"def comprehensions_{i}(xs: {ann([n, 3, d])}, w: {ann([d, k])}, short: {ann([n - 1, 3, d])}, sym: {ann([sym, 3, d])}, lst):",
        f"    x = jnp.ones(({k},)){es(x=[k])}",
        f"    stacked = jnp.stack([x @ w for x in xs]){es(stacked=[n, 3, k])}",
        f"    after = x * 2.0{es(after=[k])}",
        f"    cat = jnp.concatenate([r @ w for r in xs]){es(cat=[n * 3, k])}",
        f"    cat1 = jnp.concatenate([r @ w for r in xs], axis=1){es(cat1=[3, n * k])}",
        f"    numbered = jnp.stack([r * j for j, r in enumerate(xs)]){es(numbered=[n, 3, d])}",
        f"    paired = jnp.stack([a + b for a, b in zip(xs, xs)]){es(paired=[n, 3, d])}",
        f"    cut = jnp.stack([a[0] + b[0] for a, b in zip(xs, short)]){es(cut=[n - 1, d])}",
        f"    counted = jnp.stack([w * t for t in range(3)]){es(counted=[3, d, k])}",
        f"    indexed = jnp.stack([xs[t] for t in range(len(xs))]){es(indexed=[n, 3, d])}",
        f"    total = sum(r @ w for r in xs){es(total=[3, k])}",
        f"    total_list = sum([r @ w for r in xs]){es(total_list=[3, k])}",
        f"    nested = jnp.stack([jnp.stack([c * 2.0 for c in r]) for r in xs]){es(nested=[n, 3, d])}",
        f"    unbound = jnp.stack([r @ w for r in sym]){es(unbound=None)}",
        f"    hidden = jnp.stack([x * 1.0 for x in lst]){es(hidden=None)}",
        f"    varying = jnp.stack([jnp.zeros((t, 2)) for t in range(3)]){es(varying=None)}",
        f"    filtered = jnp.stack([r @ w for r in xs if r.sum() > 0]){es(filtered=None)}",
        f"    generated = jnp.stack(r @ w for r in xs){es(generated=None)}",
        f"    bad = jnp.stack([r @ jnp.ones(({d + 1}, 2)) for r in xs])  # expected-error: comprehension body contracts {d} with {d + 1}",
        "    return stacked, after, cat, cat1, numbered, paired, cut, counted, indexed, total, total_list, nested, unbound, hidden, varying, filtered, generated, bad",
        "",
        "",
    ]


def t_lambdas(i):
    # The parameters of a lambda are bound to the shapes of the call. vmap
    # peels one leading axis of every argument, runs the body on one example,
    # and puts the axis back at out_axes. lax.map is vmap over axis 0, and scan
    # gives the carry init and the element one row of xs. A parameter hides a
    # variable of the same name outside. A tuple result, an in_axes that is not
    # one integer, and a non-array argument stay unknown.
    n, d, k = 3 + i % 4, 8 + 2 * (i % 4), 5 + i % 3
    return [
        f"def lambdas_{i}(xs: {ann([n, 3, d])}, w: {ann([d, k])}, v: {ann([n, d])}, y: {ann([3, d])}, lst):",
        f"    x = jnp.ones((7, 7)){es(x=[7, 7])}",
        f"    direct = (lambda x: x * 2.0)(y){es(direct=[3, d])}",
        f"    keyword = (lambda a, b=2.0: a @ w * b)(a=y){es(keyword=[3, k])}",
        f"    hides = (lambda x: x * 2.0)(lst){es(hides=None)}",
        f"    mapped = jax.vmap(lambda r: r @ w)(xs){es(mapped=[n, 3, k])}",
        f"    mapped2 = jax.vmap(lambda a, b: a + b)(xs, xs){es(mapped2=[n, 3, d])}",
        f"    mapped_axis = jax.vmap(lambda r: r.sum(), in_axes=1)(xs){es(mapped_axis=[3])}",
        f"    mapped_out = jax.vmap(lambda r: r * 2.0, out_axes=1)(xs){es(mapped_out=[3, n, d])}",
        f"    twice = jax.vmap(jax.vmap(lambda r: r * 2.0))(xs){es(twice=[n, 3, d])}",
        f"    closed = jax.vmap(lambda r: r * w.sum())(xs){es(closed=[n, 3, d])}",
        f"    looped = jax.lax.map(lambda r: r @ w, xs){es(looped=[n, 3, k])}",
        f"    last, ys = jax.lax.scan(lambda c, r: (c + r, c * r), v[0], v){es(last=[d], ys=[n, d])}",
        f"    last2, ys2 = jax.lax.scan(lambda c, r: (c, r.sum()), v[0], v){es(last2=[d], ys2=[n])}",
        f"    last3, ys3 = jax.lax.scan(lambda c, r: (c, (r, r)), v[0], v){es(last3=[d], ys3=None)}",
        f"    pair = jax.vmap(lambda r: (r, r))(xs){es(pair=None)}",
        f"    tuple_axes = jax.vmap(lambda r: r * 2.0, in_axes=(0,))(xs){es(tuple_axes=None)}",
        f"    bad = jax.vmap(lambda a, b: a + b)(xs, w)  # expected-error: vmap axes {n} and {d} disagree",
        "    return direct, keyword, hides, mapped, mapped2, mapped_axis, mapped_out, twice, closed, looped, last, ys, last2, ys2, last3, ys3, pair, tuple_axes, bad",
        "",
        "",
    ]


def t_shape_names(i):
    # Names unpacked from `x.shape` stand for the dims of x, so a reshape that
    # multiplies them shows the dims' product, never the names or an internal
    # symbol. Division is not modelled, so a -1 next to a product stays unknown.
    b, n, d = f"b{i}", f"n{i}", f"d{i}"
    return [
        f"def shape_names_{i}(x: {ann([b, n, d])}):",
        "    p, q, r = x.shape",
        f"    m2 = x.reshape(p * q, r){es(m2=[prod([b, n]), d])}",
        f"    m3 = jnp.reshape(x, (p * q, r)){es(m3=[prod([b, n]), d])}",
        f"    m4 = x.reshape(p, q * r){es(m4=[b, prod([n, d])])}",
        f"    m5 = x.reshape(p * q * r){es(m5=[prod([b, n, d])])}",
        f"    m6 = x.reshape(p, q, r){es(m6=[b, n, d])}",
        f"    m7 = m6 + x{es(m7=[b, n, d])}",
        f"    m8 = rearrange(jnp.exp(x), 'p q -> q p')  # expected-error: einops pattern has rank 2, the operand rank 3",
        "    return m2, m3, m4, m5, m7, m8",
        "",
        "",
    ]


def t_scalar_operands(i):
    # A provable scalar (a number, a `math` call or constant, `len`, a shape
    # entry, a numpy/jax function of scalars, a name bound only to those) never
    # changes the array operand's shape. `jnp.sqrt(2.0)` is itself rank 0.
    t, d = f"t{i}", f"d{i}"
    return [
        f"STRESS_EPS_{i} = 1e-6",
        "",
        "",
        f"def scalar_operands_{i}(ys: {ann([t, d])}, zs: {ann([t])}, k: int):",
        f"    a = ys / jnp.sqrt(2.0){es(a=[t, d])}",
        f"    b = ys / math.sqrt(k){es(b=[t, d])}",
        f"    c = ys * math.pi{es(c=[t, d])}",
        f"    e = ys / len(zs){es(e=[t, d])}",
        f"    f = ys / (2 * jnp.sqrt(2.0)){es(f=[t, d])}",
        f"    g = ys / ys.shape[-1]{es(g=[t, d])}",
        f"    dk = ys.shape[-1]",
        f"    inv = 1.0 / math.sqrt(dk)",
        f"    h = ys * inv{es(h=[t, d])}",
        f"    n = ys / (jnp.abs(ys) + STRESS_EPS_{i}){es(n=[t, d])}",
        f"    r = jnp.sqrt(2.0){es(r=[])}",
        f"    bad = (ys / math.sqrt(2.0)) * zs  # expected-error: {d} vs {t} (the scalar divisor is ignored)",
        "    return a, b, c, e, f, g, h, n, r",
        "",
        "",
    ]


def t_bmm_cross_entropy(i):
    # torch.bmm needs rank 3 and an equal batch dim (no broadcasting).
    # F.cross_entropy: class dim is 1 (0 when unbatched); a target without the
    # class dim holds indices, a target of the input's shape holds probabilities;
    # reduction 'none' keeps the per-item shape, any other reduction is rank 0.
    b, n, m, p, c = f"b{i}", f"n{i}", f"m{i}", f"p{i}", f"c{i}"
    return [
        f"def bmm_cross_entropy_{i}(q: {ann([b, n, m])}, w: {ann([b, m, p])}, logits: {ann([b, c])}, y: {ann([b])}, probs: {ann([b, c])}, tok: {ann([b, n, c])}, tgt: {ann([b, n])}, v: {ann([c])}):",
        f"    s = torch.bmm(q, w){es(s=[b, n, p])}",
        f"    s2 = q.bmm(w){es(s2=[b, n, p])}",
        f"    s3 = torch.bmm(input=s, mat2=w.mT){es(s3=[b, n, m])}",
        f"    loss = F.cross_entropy(logits, y){es(loss=[])}",
        f"    per = F.cross_entropy(logits, y, reduction='none'){es(per=[b])}",
        f"    soft = F.cross_entropy(logits, probs, reduction='none'){es(soft=[b])}",
        f"    tok_loss = F.cross_entropy(tok.permute(0, 2, 1), tgt, reduction='none'){es(tok_loss=[b, n])}",
        f"    one = torch.nn.functional.cross_entropy(v, probs[0], reduction='none'){es(one=[])}",
        f"    nll = F.nll_loss(F.log_softmax(logits, dim=1), y, reduction='sum'){es(nll=[])}",
        f"    unknown = F.cross_entropy(logits, y, reduction=STRESS_MODE_{i})",
        f"    bad_bmm = torch.bmm(q, w[:1])  # expected-error: batch {b} vs 1 (bmm never broadcasts)",
        f"    bad_ce = F.cross_entropy(logits, tgt)  # expected-error: target {b} {n} against input {b} {c}",
        "    return s, s2, s3, loss, per, soft, tok_loss, one, nll, unknown",
        "",
        "",
    ]


def t_closure_capture(i):
    # A closure reads the enclosing function's variables when it is called, so
    # `level1` sees the reassigned `w` on its second call.
    b, n, d, e, t = f"b{i}", f"n{i}", f"d{i}", f"e{i}", f"t{i}"
    return [
        f"def closure_capture_{i}(x: {ann([b, n, d])}, w: {ann([d, e])}, W: {ann([d, d])}, xs: {ann([t, b, d])}, h0: {ann([b, d])}):",
        "    def level1(t):",
        "        u = t @ w",
        "        return u",
        "",
        f"    y = level1(x){es(y=[b, n, e])}",
        f"    w = w[:, :4]{es(w=[d, 4])}",
        f"    y2 = level1(x){es(y2=[b, n, 4])}",
        "",
        "    def level2(t):",
        "        nonlocal W",
        "        return t @ W",
        "",
        f"    z = level2(x){es(z=[b, n, d])}",
        "",
        "    def step(c, xt):",
        f"        h = jnp.tanh(c @ W + xt){es(h=[b, d])}",
        "        return h, h",
        "",
        f"    hT, ys = jax.lax.scan(step, h0, xs){es(hT=[b, d], ys=[t, b, d])}",
        "    return y2, z, ys",
        "",
        "",
    ]


def t_submodule_calls(i):
    # User modules held in fields: called directly, vmapped, mapped, and built
    # inline (flax). Constructor values reach the callee through `dim` and
    # `features`; the callee has no annotation, so it is evaluated per call.
    d = 32 + 16 * (i % 3)
    f = 2 * d
    b, s = f"b{i}", f"s{i}"
    return [
        f"class SubFfn{i}(nn.Module):",
        "    def __init__(self, dim):",
        "        super().__init__()",
        f"        self.up = nn.Linear(dim, {f})",
        f"        self.down = nn.Linear({f}, dim)",
        "",
        "    def forward(self, x):",
        "        return self.down(F.relu(self.up(x)))",
        "",
        "",
        f"class SubNet{i}(nn.Module):",
        "    def __init__(self):",
        "        super().__init__()",
        f"        self.ffn = SubFfn{i}({d})",
        f"        self.norm = nn.LayerNorm({d})",
        "",
        f"    def forward(self, x: {ann([b, s, d])}):",
        f"        h = self.ffn(x){es(h=[b, s, d])}",
        f"        y = self.norm(h + x){es(y=[b, s, d])}",
        "        return y",
        "",
        "",
        f"class SubEqx{i}(eqx.Module):",
        "    w: eqx.nn.Linear",
        "    norm: eqx.nn.LayerNorm",
        "",
        "    def __init__(self, key):",
        f"        self.w = eqx.nn.Linear({d}, {f}, key=key)",
        f"        self.norm = eqx.nn.LayerNorm({f})",
        "",
        "    def __call__(self, x):",
        f"        return self.norm(self.w(x))",
        "",
        "",
        f"class SubEqxModel{i}(eqx.Module):",
        f"    blk: SubEqx{i}",
        "    norm: eqx.nn.LayerNorm",
        "",
        "    def __init__(self, key):",
        f"        self.blk = SubEqx{i}(key)",
        f"        self.norm = eqx.nn.LayerNorm({f})",
        "",
        f"    def __call__(self, x: {ann([s, d])}, r: {ann([s, f])}):",
        f"        h = jax.vmap(self.blk)(x){es(h=[s, f])}",
        f"        z = jax.vmap(self.norm)(h + r){es(z=[s, f])}",
        f"        q = jax.vmap(self.norm)(jax.nn.gelu(h) * 2.0 + r){es(q=[s, f])}",
        f"        u = jax.lax.map(self.blk, x){es(u=[s, f])}",
        "        return z, q, u",
        "",
        "",
        f"class SubFlaxBlock{i}(fnn.Module):",
        "    features: int",
        "",
        "    @fnn.compact",
        "    def __call__(self, x):",
        "        return fnn.Dense(self.features)(x)",
        "",
        "",
        f"class SubFlaxNet{i}(fnn.Module):",
        "    @fnn.compact",
        f"    def __call__(self, x: {ann([b, d])}):",
        f"        y = SubFlaxBlock{i}(features={f})(x){es(y=[b, f])}",
        f"        z = SubFlaxBlock{i}({d})(x){es(z=[b, d])}",
        "        return y, z",
        "",
        "",
    ]


def t_loss_layers(i):
    # torch.nn loss modules take the prediction and a target. The cross-entropy
    # pair follows F.cross_entropy / F.nll_loss: the class dim is 1, a target of
    # the input's shape holds probabilities (cross entropy only), and the
    # constructor reduction picks the per-item shape or a scalar. The regression
    # losses broadcast their operands (torch warns, it does not raise), so a
    # column against a row gives the matrix, and only integer dims that differ
    # fail. BCELoss and BCEWithLogitsLoss never broadcast: a rank that differs is
    # an error. HuberLoss takes `reduction` first. A reduction that depends on a
    # value, or on the deprecated size_average / reduce, stays unknown.
    b, c = f"b{i}", f"c{i}"
    return [
        f"STRESS_LOSS_MODE_{i} = 'none'",
        "",
        "",
        f"class LossHolder_{i}(nn.Module):",
        "    def __init__(self):",
        "        super().__init__()",
        "        self.crit = nn.CrossEntropyLoss(reduction='none')",
        "        self.mse = nn.MSELoss()",
        "",
        f"    def forward(self, logits: {ann([b, c])}, y: {ann([b])}, pred: {ann([b, c])}):",
        f"        per = self.crit(logits, y){es(per=[b])}",
        f"        mean = self.mse(pred, pred){es(mean=[])}",
        f"        both = self.crit(logits, y).sum() + self.mse(pred, pred){es(both=[])}",
        "        return per, mean, both",
        "",
        "",
        f"def loss_layers_{i}(logits: {ann([b, c])}, y: {ann([b])}, probs: {ann([b, c])}, pred: {ann([b, c])}, tgt: {ann([b, c])}, row: {ann([c])}, col: {ann([b, 1])}, flat: {ann([b])}, four: {ann([4, 3])}, five: {ann([5, 3])}):",
        "    ce = nn.CrossEntropyLoss()",
        f"    l1 = ce(logits, y){es(l1=[])}",
        "    ce_none = nn.CrossEntropyLoss(reduction='none')",
        f"    l2 = ce_none(logits, y){es(l2=[b])}",
        f"    l3 = ce_none(logits, probs){es(l3=[b])}",
        "    nll = nn.NLLLoss(reduction='sum')",
        f"    l4 = nll(F.log_softmax(logits, dim=1), y){es(l4=[])}",
        f"    l5 = nn.MSELoss()(pred, tgt){es(l5=[])}",
        f"    l6 = nn.MSELoss(reduction='none')(pred, row){es(l6=[b, c])}",
        f"    l7 = nn.L1Loss(reduction='none')(pred, col){es(l7=[b, c])}",
        f"    l8 = nn.SmoothL1Loss(reduction='sum')(pred, tgt){es(l8=[])}",
        f"    l9 = nn.HuberLoss('none')(pred, tgt){es(l9=[b, c])}",
        f"    l10 = nn.BCELoss(reduction='none')(pred, tgt){es(l10=[b, c])}",
        f"    l11 = nn.BCEWithLogitsLoss()(pred, tgt){es(l11=[])}",
        f"    l12 = nn.MSELoss(reduction=STRESS_LOSS_MODE_{i})(pred, tgt){es(l12=None)}",
        f"    l13 = nn.MSELoss(size_average=False)(pred, tgt){es(l13=None)}",
        f"    bad_bce = nn.BCELoss()(pred, flat)  # expected-error: BCELoss needs the input rank, {b} against {b} {c}",
        f"    bad_mse = nn.MSELoss()(four, five)  # expected-error: dim 0 is 4 against 5",
        "    return l1, l2, l3, l4, l5, l6, l7, l8, l9, l10, l11, l12, l13",
        "",
        "",
    ]


def t_module_containers(i):
    # User modules held in a ModuleList, a Sequential, or a list. A Sequential
    # applies its elements in order. A loop `x = layer(x)` over a list is the
    # same chain, with the elements in order. An index picks one element, and an
    # unknown index is known only if every element agrees. One call repeated by
    # a comprehension is the same module each time, so it keeps a shape only if
    # one application gives the shape back, because the count may be anything.
    # The index `k` and the count `depth` are not in the file, so the results
    # that depend on them stay unknown.
    d = 32 + 16 * (i % 3)
    h, o = 2 * d, d // 2
    b, s = f"b{i}", f"s{i}"
    blk, strict = f"McBlock{i}", f"McStrict{i}"
    x = [b, s, d]
    return [
        f"class {blk}(nn.Module):",
        "    def __init__(self, d_in, d_out):",
        "        super().__init__()",
        "        self.fc = nn.Linear(d_in, d_out)",
        "",
        "    def forward(self, x):",
        "        return F.relu(self.fc(x))",
        "",
        "",
        f"class {strict}(nn.Module):",
        "    def __init__(self, d_out):",
        "        super().__init__()",
        f"        self.fc = nn.Linear({d}, d_out)",
        "",
        f"    def forward(self, x: {ann([f'p{i}', f'q{i}', d])}):",
        "        return self.fc(x)",
        "",
        "",
        f"class McNet{i}(nn.Module):",
        "    def __init__(self, depth):",
        "        super().__init__()",
        f"        self.layers = nn.ModuleList([{blk}({d}, {h}), {blk}({h}, {o})])",
        f"        self.same = nn.ModuleList([{blk}({d}, {d}) for _ in range(3)])",
        f"        self.seq = nn.Sequential({blk}({d}, {h}), nn.ReLU(), {blk}({h}, {o}))",
        f"        self.grow = nn.ModuleList([{blk}({d}, {h}) for _ in range(depth)])",
        f"        self.mixed = nn.ModuleList([nn.Linear({d}, {h}), nn.GELU(), {blk}({h}, {o})])",
        f"        self.bad = nn.Sequential({strict}({h}), {strict}({o}))",
        "",
        f"    def forward(self, x: {ann(x)}, k: int):",
        f"        a = self.seq(x){es(a=[b, s, o])}",
        "        h = x",
        "        for layer in self.layers:",
        f"            h = layer(h){es(h=[b, s, o])}",
        f"        after = h{es(after=[b, s, o])}",
        "        r = x",
        "        for layer in self.same:",
        f"            r = layer(r){es(r=x)}",
        f"        e = self.layers[0](x){es(e=[b, s, h])}",
        f"        f = self.layers[-1](e){es(f=[b, s, o])}",
        f"        g = self.layers[k](x){es(g=None)}",
        f"        m = self.same[k](x){es(m=x)}",
        "        mixed = x",
        "        for layer in self.mixed:",
        f"            mixed = layer(mixed){es(mixed=[b, s, o])}",
        "        gr = x",
        "        for layer in self.grow:",
        f"            gr = layer(gr){es(gr=None)}",
        "        t = x",
        "        for layer in self.same:",
        f"            u = layer(t){es(u=x)}",
        f"            t = F.relu(u){es(t=x)}",
        f"        bad = self.bad(x)  # expected-error: second element expects {d}, gets {h}",
        "        return a, after, r, f, g, m, mixed, gr, t",
        "",
        "",
        # A list that other code keeps under another name, reaches by a string,
        # or takes from an instance may hold what the constructor did not put
        # in it: `extra` is any module. Reading a list (a loop, `len`) keeps it.
        f"class McAlias{i}(nn.Module):",
        "    def __init__(self):",
        "        super().__init__()",
        f"        self.layers = nn.ModuleList([{blk}({d}, {d})])",
        f"        self.hidden = nn.ModuleList([{blk}({d}, {d})])",
        f"        self.outer = nn.ModuleList([{blk}({d}, {d})])",
        f"        self.plain = nn.ModuleList([{blk}({d}, {d})])",
        "",
        "    def grow(self, extra):",
        "        ls = self.layers",
        "        ls.append(extra)",
        '        getattr(self, "hidden").append(extra)',
        "",
        f"    def forward(self, x: {ann(x)}):",
        "        y = x",
        "        for layer in self.layers:",
        f"            y = layer(y){es(y=None)}",
        "        z = x",
        "        for layer in self.hidden:",
        f"            z = layer(z){es(z=None)}",
        "        o = x",
        "        for layer in self.outer:",
        f"            o = layer(o){es(o=None)}",
        "        u = x",
        "        for layer in self.plain:",
        f"            u = layer(u){es(u=x)}",
        "        n = len(self.plain)",
        "        return y, z, o, u, n",
        "",
        "",
        f"mc_alias_{i} = McAlias{i}()",
        f"mc_outer_{i} = mc_alias_{i}.outer",
        f"mc_outer_{i}.append(None)",
        "",
        "",
    ]


