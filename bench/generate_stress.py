def fmt(shape):
    return "[" + ", ".join(str(d) for d in shape) + "]"


def prod(dims):
    if all(isinstance(d, int) for d in dims):
        r = 1
        for d in dims:
            r *= d
        return r
    return "*".join(str(d) for d in dims)


def ann(shape):
    return 'Float[Array, "' + " ".join(str(d) for d in shape) + '"]'


def es(**kw):
    return "  # expected-shape: " + "; ".join(f"{k}={fmt(v)}" for k, v in kw.items())


def eshape(pairs):
    return "  # expected-shape: " + "; ".join(f"{k}={fmt(v)}" for k, v in pairs)


