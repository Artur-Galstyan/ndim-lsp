def t_deep_hierarchy(i):
    """4-level chain. Odd instances use unique attr names, even instances use the
    common names (l0, l1, ...) that every other hierarchy also defines."""
    dims = [G.num() for _ in range(5)]
    b = f"b{i}"
    u = f"_{i}" if i % 2 else ""
    L = []
    prev = None
    for lvl in range(4):
        name = f"Level{lvl}_{i}"
        base = f"({prev})" if prev else "(nn.Module)"
        L.append(f"class {name}{base}:")
        L.append("    def __init__(self):")
        L.append("        super().__init__()")
        L.append(f"        self.l{lvl}{u} = nn.Linear({dims[lvl]}, {dims[lvl + 1]})")
        L.append(f"        self.act{lvl}{u} = nn.ReLU()")
        L.append("")
        if lvl == 3:
            L.append(f"    def forward(self, x: {ann([b, dims[0]])}):")
            cur = "x"
            for k in range(4):
                nm = f"h{k}"
                L.append(f"        {nm} = self.l{k}{u}({cur}){es(**{nm: [b, dims[k + 1]]})}")
                nm2 = f"a{k}"
                L.append(f"        {nm2} = self.act{k}{u}({nm}){es(**{nm2: [b, dims[k + 1]]})}")
                cur = nm2
            L.append("        return a3")
        else:
            L.append(f"    def step(self, x: {ann([b, dims[lvl]])}):")
            L.append(f"        y = self.l{lvl}{u}(x){es(y=[b, dims[lvl + 1]])}")
            L.append("        return y")
        L.append("")
        L.append("")
        prev = name
    return L


def t_torch_conv(i):
    C0 = G.pick([1, 3])
    H = G.pick([28, 32, 48, 64])
    W = H
    Cs = [G.pick([8, 16, 24]), G.pick([32, 48]), G.pick([64, 96])]
    b = f"b{i}"
    L = [f"class ConvNet{i}(nn.Module):", "    def __init__(self):", "        super().__init__()"]
    pool = 2
    while True:
        cin, cfg, h, w = C0, [], H, W
        ok = True
        for n, c in enumerate(Cs):
            k = G.pick([3, 5])
            p = k // 2 if G.r.random() < 0.7 else 0
            st = G.pick([1, 1, 2])
            h = (h + 2 * p - k) // st + 1
            w = (w + 2 * p - k) // st + 1
            ok = ok and h >= pool and w >= pool
            h = (h - pool) // pool + 1
            w = (w - pool) // pool + 1
            cfg.append((cin, c, k, st, p))
            cin = c
        if ok and h >= 1:
            break
    for n, (ci, co, k, st, p) in enumerate(cfg):
        L.append(f"        self.conv{n} = nn.Conv2d({ci}, {co}, {k}, stride={st}, padding={p})")
        L.append(f"        self.bn{n} = nn.BatchNorm2d({co})")
    L.append(f"        self.pool = nn.MaxPool2d({pool})")
    # compute final spatial dims first
    h, w = H, W
    for (ci, co, k, st, p) in cfg:
        h = (h + 2 * p - k) // st + 1
        w = (w + 2 * p - k) // st + 1
        h = (h - pool) // pool + 1
        w = (w - pool) // pool + 1
    flat = Cs[-1] * h * w
    nc = G.pick([10, 100])
    L.append(f"        self.fc = nn.Linear({flat}, {nc})")
    L.append("")
    L.append(f"    def forward(self, x: {ann([b, C0, H, W])}):")
    h, w = H, W
    cur = "x"
    for n, (ci, co, k, st, p) in enumerate(cfg):
        h = (h + 2 * p - k) // st + 1
        w = (w + 2 * p - k) // st + 1
        L.append(f"        c{n} = self.conv{n}({cur}){es(**{f'c{n}': [b, co, h, w]})}")
        L.append(f"        n{n} = self.bn{n}(c{n}){es(**{f'n{n}': [b, co, h, w]})}")
        L.append(f"        r{n} = F.relu(n{n}){es(**{f'r{n}': [b, co, h, w]})}")
        h = (h - pool) // pool + 1
        w = (w - pool) // pool + 1
        L.append(f"        p{n} = self.pool(r{n}){es(**{f'p{n}': [b, co, h, w]})}")
        cur = f"p{n}"
    L.append(f"        f = {cur}.flatten(1){es(f=[b, flat])}")
    L.append(f"        logits = self.fc(f){es(logits=[b, nc])}")
    L.append("        return logits")
    L.append("")
    L.append("")
    return L


